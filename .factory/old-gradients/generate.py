NAMES = {"aurora": "Aurora", "sunset": "Sunset", "mono": "Mono", "ocean": "Ocean"}
def rgb(h): h = h.lstrip("#"); return np.array([int(h[i:i+2], 16) for i in (0, 2, 4)], float)
def render(stops, seed, w, h):
    rng = np.random.default_rng(seed)
    y, x = np.mgrid[0:h, 0:w].astype(float); x /= w; y /= h
    ang = rng.uniform(-0.5, 0.5)
    t = y * math.cos(ang) + x * math.sin(ang)                      # base direction
    for _ in range(3):                                              # soft blobs bend the gradient
        cx, cy, r = rng.uniform(0, 1), rng.uniform(0, 1), rng.uniform(0.25, 0.6)
        t += rng.uniform(-0.25, 0.35) * np.exp(-(((x-cx)**2 + (y-cy)**2) / (2*r*r)))
    t = np.clip((t - t.min()) / (t.max() - t.min()), 0, 1)
    c = [rgb(s) for s in stops]; out = np.zeros((h, w, 3))
    seg = np.minimum((t * (len(c)-1)).astype(int), len(c)-2); f = t * (len(c)-1) - seg
    f = f*f*(3-2*f)                                                 # smoothstep
    for i in range(len(c)-1):
        m = seg == i; out[m] = c[i] * (1-f[m, None]) + c[i+1] * f[m, None]
    out += rng.normal(0, 1.6, (h, w, 1))                            # fine grain hides banding
    return Image.fromarray(np.clip(out, 0, 255).astype("uint8"))
def main():
    for d in ("full", "thumbs"): os.makedirs(f"{ROOT}/{d}", exist_ok=True)
    cats, items, n = [], [], 0
    for ci, (cat, lst) in enumerate(PALETTES.items(), 1):
        cats.append({"id": cat, "name": NAMES[cat], "order": ci})
        for name, stops in lst:
            n += 1; wid = f"{cat}-{n:03d}"; im = render(stops, n * 7919, W, H)
            im.save(f"{ROOT}/full/{wid}.webp", "WEBP", quality=84, method=6)
            im.resize((TW, TH), Image.LANCZOS).save(f"{ROOT}/thumbs/{wid}.webp", "WEBP", quality=80, method=6)
            items.append({"id": wid, "title": name, "category": cat, "tags": [cat, "gradient", "abstract"],
                          "thumb": f"thumbs/{wid}.webp", "full": f"full/{wid}.webp", "width": W, "height": H,
                          "color": stops[1], "premium": False, "added": "2026-11-03", "credit": "Generated by the studio"})
    json.dump({"version": 1, "updated": "2026-11-03", "base_url": BASE, "categories": cats, "wallpapers": items},
              open(f"{ROOT}/wallpapers.json", "w"), indent=2)
    print(n, "wallpapers")
main()
